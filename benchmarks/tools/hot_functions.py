"""Chooses the functions to run from RAM from a profile that measure.py
--profile saved, and writes them one per line for rename_hot.py.

Each sample is credited to the input section of the linker map that holds it,
so only functions compiled into a section of their own, .text.<name>, are
candidates; the idle task is left out. Candidates are taken densest first,
in samples per byte, until the RAM budget is spent. A name that several
objects define moves every copy, and all copies count against the budget.

Usage: hot_functions.py <profile.txt> <elf.map> --budget <bytes> --out <file>
"""

import argparse
import bisect
import sys
from collections import defaultdict
from datetime import datetime

from profile_report import IDLE_FUNCTIONS, parse_profile, read_objects


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("profile")
    parser.add_argument("map")
    parser.add_argument("--budget", type=int, required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    buckets, totals = parse_profile(args.profile)
    base, shift = int(totals["base"], 16), int(totals["shift"])
    sections = read_objects(args.map)
    starts = [section[0] for section in sections]

    samples = defaultdict(int)
    sizes = defaultdict(int)
    for _, size, _, name in sections:
        sizes[name] += size
    unplaced = 0
    for index, count in buckets.items():
        address = base + (index << shift)
        i = bisect.bisect_right(starts, address) - 1
        if i >= 0 and address < sections[i][0] + sections[i][1]:
            samples[sections[i][3]] += count
        else:
            unplaced += count

    idle = {f".text.{name}" for name in IDLE_FUNCTIONS}
    busy = sum(n for name, n in samples.items() if name not in idle) + unplaced
    candidates = [(n / sizes[name], n, name) for name, n in samples.items()
                  if name not in idle and name.startswith(".text.") and name != ".text"]
    candidates.sort(reverse=True)

    chosen = []
    used = covered = 0
    for _, n, name in candidates:
        if used + sizes[name] > args.budget:
            continue
        chosen.append(name)
        used += sizes[name]
        covered += n

    header = [
        f"# Generated by tools/hot_functions.py on {datetime.now():%Y-%m-%d %H:%M} from",
        f"# {args.profile}",
        f"# budget {args.budget} B: {len(chosen)} functions, {used} B, {100 * covered / busy:.1f} % of the busy",
        f"# flash samples ({unplaced} samples fell outside any .text section and cannot move).",
    ]
    lines = header + [name[len(".text."):] for name in chosen]
    with open(args.out, "w") as out:
        out.write("\n".join(lines) + "\n")
    print("\n".join(header))
    return 0


if __name__ == "__main__":
    sys.exit(main())
